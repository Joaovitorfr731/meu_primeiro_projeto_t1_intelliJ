public class Main {
    static void main() {
        int numero1 = 10;
        int numero2 = 20;

        System.out.println("1 - Comparação de Dois Números");

        System.out.println("numero1 > numero2: " + (numero1 > numero2));
        System.out.println("numero1 < numero2: " + (numero1 < numero2));
        System.out.println("numero1 >= numero2: " + (numero1 >= numero2));
        System.out.println("numero1 <= numero2: " + (numero1 <= numero2));
        System.out.println("numero1 == numero2: " + (numero1 == numero2));
        System.out.println("numero1 != numero2: " + (numero1 != numero2));

    }
}
